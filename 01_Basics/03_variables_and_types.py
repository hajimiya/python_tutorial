# Python is dynamically typed, so you do not need to declare a variable's type.
name = "Ali"
age = 20
height = 1.72
is_student = True
print(name, age, height, is_student)
print(type(name), type(age), type(height), type(is_student))
age = "twenty"  # A variable can refer to a value of a different type later.
print(age, type(age))
